const (
	acute      = "..#"
	grave      = "#.."
	circumflex = ".#."
	tilde      = "###"
	cedilla    = ".#."
)

var accented = map[rune]struct {
	base  rune
	above string
	below string
}{
	'Á': {'A', acute, ""},
	'À': {'A', grave, ""},
	'Â': {'A', circumflex, ""},
	'Ã': {'A', tilde, ""},
	'É': {'E', acute, ""},
	'Ê': {'E', circumflex, ""},
	'Í': {'I', acute, ""},
	'Ó': {'O', acute, ""},
	'Ô': {'O', circumflex, ""},
	'Õ': {'O', tilde, ""},
	'Ú': {'U', acute, ""},
	'Ç': {'C', "", cedilla},
}

func Lookup(r rune) (Glyph, bool) {
	if r == ' ' {
		return Glyph{}, true
	}
	if rows, ok := base[r]; ok {
		return Glyph{Rows: rows}, true
	}
	if a, ok := accented[r]; ok {
		return Glyph{Rows: base[a.base], Above: a.above, Below: a.below}, true
	}
	return Glyph{}, false
}

func Missing(text string) []rune {
	var out []rune
	for _, r := range text {
		if _, ok := Lookup(r); !ok {
			out = append(out, r)
		}
	}
	return out
}

func Upper(text string) string {
	runes := []rune(text)
	for i, r := range runes {
		if r != 'x' {
			runes[i] = unicode.ToUpper(r)
		}
	}
	return string(runes)
}
